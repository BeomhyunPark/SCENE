const { chromium } = require('playwright');
const out = process.argv[2];
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, permissions: ['clipboard-read','clipboard-write'] });
  const p = await ctx.newPage();
  const log = [];
  p.on('pageerror', e => log.push('pageerror ' + e.message));
  await p.goto('http://localhost:5199/');
  await p.waitForFunction(() => window.sceneMock && navigator.serviceWorker.controller, null, { timeout: 15000 });
  const RETREAT = await p.evaluate(async () => {
    const seed = await import('/src/test/summarySeed.ts');
    const ci = await import('/src/mocks/checkInStore.ts');
    const ps = await import('/src/mocks/participantStore.ts');
    const mc = await import('/src/mocks/mealCounts.ts');
    const fx = await import('/src/mocks/fixtures/seed.ts');
    const session = await import('/src/api/session.ts');
    const r = seed.seedRetreat();
    const ids = [];
    const names = [['하나','94','opt_female'],['두리','95','opt_male'],['세나','96','opt_female'],['네온','97','opt_male']];
    for (const [n,c,g] of names) ids.push(r.apply({ NAME: n, COHORT: c, GENDER: { optionId: g }, ATTENDANCE: { optionId: 'opt_full' } }));
    ids.push(r.apply({ NAME: '세찬', COHORT: '96', GENDER: { optionId: 'opt_male' }, ATTENDANCE: { optionId: 'opt_partial' }, MEALS: { optionIds: ['opt_d2_lunch','opt_d2_dinner'] } }));
    const part = (a) => ps.tableApplications(seed.RETREAT).find((row) => row.applicationId === a).participantId;
    ci.seedCheckIn(seed.RETREAT, part(ids[0])); ci.seedCheckIn(seed.RETREAT, part(ids[1]));
    mc.setMealCountsNow(new Date('2027-01-22T19:10:00+09:00'));
    await session.login({ userId: fx.localUsers[0].userId });
    return seed.RETREAT;
  });
  // client-side navigation keeps in-page stores
  await p.evaluate((id) => { history.pushState({}, '', `/events/${id}/meals`); dispatchEvent(new PopStateEvent('popstate')); }, RETREAT);
  await p.getByRole('button', { name: '다음 식사 복사' }).waitFor({ timeout: 15000 });
  await p.screenshot({ path: `${out}/7-wording-next.png` });
  const btns = await p.locator('.meals__actions button').evaluateAll(els => els.map(e => ({ text: e.innerText, h: e.getBoundingClientRect().height, w: e.getBoundingClientRect().width, sw: e.scrollWidth, cw: e.clientWidth })));
  log.push('buttons ' + JSON.stringify(btns));
  await p.getByRole('button', { name: '다음 식사 복사' }).click();
  await p.getByText('다음 식사를 복사했어요').waitFor();
  log.push('clip(next):\n' + await p.evaluate(() => navigator.clipboard.readText()));
  await p.screenshot({ path: `${out}/8-wording-copied.png` });
  await p.getByRole('button', { name: '남은 식사 복사' }).click();
  await p.getByText('남은 식사를 복사했어요').waitFor();
  log.push('clip(rest):\n' + await p.evaluate(() => navigator.clipboard.readText()));
  await p.locator('summary', { hasText: '숫자는 이렇게 나와요' }).click();
  await p.locator('.meals__how').scrollIntoViewIfNeeded();
  await p.screenshot({ path: `${out}/9-wording-how.png` });
  log.push('page has 끼니: ' + (await p.locator('body').innerText()).includes('끼니'));
  log.push('table label: ' + await p.getByRole('region', { name: '식사별 식수' }).count());
  console.log(log.join('\n'));
  await b.close();
})().catch(e => { console.error(e); process.exit(1); });
