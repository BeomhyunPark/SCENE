  @Test
  void mixedAttendanceGivesSlotsPerParticipantThatAddUpToTheSummary() throws Exception {
    Held event = openEvent("Mixed owner");
    Form form = setupForm(event, setup(true, SCHEDULE));
    form.submit("가람", 1, values("ATTENDANCE", opt("opt_full")));
    form.submit(
        "나래",
        2,
        values(
            "ATTENDANCE",
            opt("opt_partial"),
            "ARRIVAL_AT",
            "{\"dateTime\":\"2027-01-23T11:00\"}",
            "DEPARTURE_AT",
            "{\"dateTime\":\"2027-01-24T09:00\"}",
            "MEALS",
            opts("opt_d2_worship", "opt_d2_lunch", "opt_d2_dinner")));
    form.submit(
        "다솜",
        3,
        values(
            "ATTENDANCE", opt("opt_worship"), "MEALS", opts("opt_d1_worship", "opt_d2_worship")));
    // Partial, but the MEALS answer is gone, as for an application from before the question.
    form.submit(
        "마루",
        4,
        values(
            "ATTENDANCE",
            opt("opt_partial"),
            "ARRIVAL_AT",
            "{\"dateTime\":\"2027-01-22T18:00\"}",
            "DEPARTURE_AT",
            "{\"dateTime\":\"2027-01-22T22:00\"}",
            "MEALS",
            opts("opt_d1_dinner")));
    form.dropAnswer("마루", "MEALS");
    // Full: a stray meal answer is dropped by the condition and does not narrow the slots.
    form.submit("바다", 5, values("ATTENDANCE", opt("opt_full"), "MEALS", opts("opt_d3_breakfast")));

    JsonNode board = board(event);
    assertThat(board.propertyNames())
        .containsExactly(
            "eventStatus",
            "boardVersion",
            "groups",
            "participants",
            "withdrawn",
            "publication",
            "slots");
    JsonNode slots = board.get("slots");
    assertThat(slotIds(slots)).isEqualTo(ALL);
    assertThat(slots.get(0).toString())
        .isEqualTo(
            "{\"slotId\":\"opt_d1_dinner\",\"day\":1,\"date\":\"2027-01-22\","
                + "\"dayLabel\":\"1월 22일 (금)\",\"meal\":\"DINNER\",\"label\":\"저녁\","
                + "\"sortOrder\":0}");
    assertThat(slots.get(5).get("meal").asString()).isEqualTo("WORSHIP");
    assertThat(slots.get(5).get("label").asString()).isEqualTo("집회");
    assertThat(slots.get(6).get("day").asInt()).isEqualTo(3);
    assertThat(slots.get(6).get("sortOrder").asInt()).isEqualTo(6);

    JsonNode participants = board.get("participants");
    assertThat(participants.get(0).propertyNames()).endsWith("publishedLeader", "slotIds");
    assertThat(attended(board, "가람")).isEqualTo(ALL);
    assertThat(attended(board, "바다")).isEqualTo(ALL);
    // In slot order, whatever order the answer listed them in.
    assertThat(attended(board, "나래"))
        .containsExactly("opt_d2_lunch", "opt_d2_dinner", "opt_d2_worship");
    assertThat(attended(board, "다솜")).containsExactly("opt_d1_worship", "opt_d2_worship");
    assertThat(person(board, "마루").get("attendance").asString()).isEqualTo("PARTIAL");
    assertThat(person(board, "마루").get("slotIds").isNull()).isTrue();

    assertSameAsSummary(event, board, 1);
  }

  @Test
  void turnedOffQuestionsFollowTheSummary() throws Exception {
    Held event = openEvent("Off owner");
    Form form = setupForm(event, setup(true, SCHEDULE));
    form.submit("가람", 1, values("ATTENDANCE", opt("opt_full")));
    form.submit(
        "나래",
        2,
        values(
            "ATTENDANCE",
            opt("opt_partial"),
            "ARRIVAL_AT",
            "{\"dateTime\":\"2027-01-22T18:00\"}",
            "DEPARTURE_AT",
            "{\"dateTime\":\"2027-01-24T09:00\"}",
            "MEALS",
            opts("opt_d1_dinner")));
    form.submit("다솜", 3, values("ATTENDANCE", opt("opt_worship"), "MEALS", opts("opt_d1_worship")));

    // MEALS off: slots stay, full attendees attend all, the others are unknown.
    form.hide("MEALS");
    JsonNode noMeals = board(event);
    assertThat(slotIds(noMeals.get("slots"))).isEqualTo(ALL);
    assertThat(attended(noMeals, "가람")).isEqualTo(ALL);
    assertThat(person(noMeals, "나래").get("slotIds").isNull()).isTrue();
    assertThat(person(noMeals, "다솜").get("slotIds").isNull()).isTrue();
    assertSameAsSummary(event, noMeals, 2);

    // ATTENDANCE off as well: everyone attends in full (DEC-072), so everyone has every slot.
    form.hide("ATTENDANCE");
    JsonNode allFull = board(event);
    for (String name : List.of("가람", "나래", "다솜")) {
      assertThat(attended(allFull, name)).as(name).isEqualTo(ALL);
    }
    assertSameAsSummary(event, allFull, 0);
  }

  @Test
  void setupWithoutAttendanceQuestionGivesEveryoneEverySlot() throws Exception {
    Held event = openEvent("No attendance owner");
    Form form = setupForm(event, setup(false, SCHEDULE));
    assertThat(form.fieldIds).doesNotContainKeys("ATTENDANCE", "MEALS");
    form.submit("가람", 1, values());
    form.submit("나래", 2, values());

    JsonNode board = board(event);
    assertThat(slotIds(board.get("slots"))).isEqualTo(ALL);
    assertThat(attended(board, "가람")).isEqualTo(ALL);
    assertThat(attended(board, "나래")).isEqualTo(ALL);
    assertSameAsSummary(event, board, 0);
  }

  @Test
  void noSetupOrNoSlotGivesNullSlots() throws Exception {
    // A form made without the setup card.
    Held plain = openEvent("Plain owner");
    period(plain);
    String formId =
        json.readTree(created(write(post(forms(plain)), plain.owner, "{}")))
            .get("formId")
            .asString();
    Form plainForm = open(plain, formId);
    plainForm.submit("가람", 1, values());
    JsonNode plainBoard = board(plain);
    assertThat(plainBoard.get("slots").isNull()).isTrue();
    assertThat(person(plainBoard, "가람").get("slotIds").isNull()).isTrue();

    // A setup whose schedule has no meal and no worship service.
    Held empty = openEvent("Empty owner");
    Form emptyForm = setupForm(empty, setup(true, NO_SLOTS));
    assertThat(emptyForm.fieldIds).doesNotContainKey("MEALS");
    emptyForm.submit("나래", 2, values("ATTENDANCE", opt("opt_full")));
    JsonNode emptyBoard = board(empty);
    assertThat(emptyBoard.get("slots").isNull()).isTrue();
    assertThat(person(emptyBoard, "나래").get("slotIds").isNull()).isTrue();
    assertThat(summary(empty).get("meals").isNull()).isTrue();

    // An event without participants still lists the slots.
    Held none = openEvent("None owner");
    setupForm(none, setup(true, SCHEDULE));
    JsonNode noneBoard = board(none);
    assertThat(slotIds(noneBoard.get("slots"))).isEqualTo(ALL);
    assertThat(noneBoard.get("participants").size()).isZero();
  }

  @Test
  void participantGroupHasNoSlots() throws Exception {
    Held event = openEvent("Participant owner");
    Form form = setupForm(event, setup(true, SCHEDULE));
    String phone =
        form.submit(
            "나래",
            1,
            values(
                "ATTENDANCE",
                opt("opt_partial"),
                "ARRIVAL_AT",
                "{\"dateTime\":\"2027-01-22T18:00\"}",
                "DEPARTURE_AT",
                "{\"dateTime\":\"2027-01-24T09:00\"}",
                "MEALS",
                opts("opt_d1_dinner")));
    String participantId = person(board(event), "나래").get("participantId").asString();
    String groupId =
        json.readTree(created(write(post(groupsPath(event)), event.owner, "{\"name\":\"1조\"}")))
            .get("group")
            .get("groupId")
            .asString();
    ok(
        write(
            post("/api/v1/operator/events/" + event.eventId + "/group-assignments"),
            event.owner,
            "{\"changes\":[{\"participantId\":\""
                + participantId
                + "\",\"fromGroupId\":null,\"toGroupId\":\""
                + groupId
                + "\"}]}"));
    long version = board(event).get("boardVersion").asLong();
    ok(
        write(
            post(groupsPath(event) + "/publish"),
            event.owner,
            "{\"expectedBoardVersion\":" + version + ",\"confirmUnassigned\":true}"));

    String mine =
        mvc.perform(get("/api/v1/participant/group").cookie(participantSession(event, "나래", phone)))
            .andExpect(status().isOk())
            .andReturn()
            .getResponse()
            .getContentAsString();
    assertThat(json.readTree(mine).get("status").asString()).isEqualTo("ASSIGNED");
    assertThat(mine).doesNotContain("slot").doesNotContain("opt_d1");
  }

